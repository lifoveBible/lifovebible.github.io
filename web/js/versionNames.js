/**
 * 코드(대소문자 무관)의 정식 이름. 화면 언어가 ko면 한국어 이름. 표에 없으면 null
 * @param {string} code
 * @param {string} [lang] 화면 언어
 */
export function officialName(code, lang) {
  const v = NAMES[String(code || '').toLowerCase()];
  if (!v) return null;
  return (lang === 'ko' && v[1]) || v[0];
}

